#!/usr/bin/env bash
#
# sync_core_ts.sh — copy the testable TypeScript core into the Lens Studio project.
#
# Source of truth : packages/waykin-core-ts/src/*.ts
# Generated copy  : spectacles/WaykinLens/Assets/Scripts/core/*.ts
#
# Usage:
#   bash scripts/sync_core_ts.sh           # regenerate the Lens copy in place
#   bash scripts/sync_core_ts.sh --check   # regenerate into a temp dir and diff
#
# The Lens copy is generated output. Never edit it by hand: edit the package,
# run this script, and commit both sides together.

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# Repo root: prefer git (works from any subdirectory of the work tree), fall
# back to "parent of this script's directory" when git is unavailable.
if REPO_ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel 2>/dev/null)"; then
  :
else
  REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
fi

SRC_DIR="$REPO_ROOT/packages/waykin-core-ts/src"
DEST_DIR="$REPO_ROOT/spectacles/WaykinLens/Assets/Scripts/core"
DEST_LABEL="spectacles/WaykinLens/Assets/Scripts/core"
HEADER='// GENERATED by scripts/sync_core_ts.sh from packages/waykin-core-ts/src — do not edit'

usage() {
  cat <<'EOF'
Usage: scripts/sync_core_ts.sh [--check]

  (no args)   Regenerate spectacles/WaykinLens/Assets/Scripts/core from
              packages/waykin-core-ts/src and delete stale *.ts files there.
  --check     Regenerate into a temporary directory and diff it against the
              committed copy. Exits 1 (with a message) when they differ.

  -h, --help  Show this help.
EOF
}

MODE="sync"
case "${1:-}" in
  "")
    MODE="sync"
    ;;
  --check)
    MODE="check"
    ;;
  -h|--help)
    usage
    exit 0
    ;;
  *)
    echo "sync_core_ts.sh: unknown argument: $1" >&2
    echo >&2
    usage >&2
    exit 2
    ;;
esac

if [ ! -d "$SRC_DIR" ]; then
  echo "sync_core_ts.sh: source directory not found: $SRC_DIR" >&2
  exit 1
fi

# render <out-dir>
#
# Writes every "$SRC_DIR"/*.ts as "<header>\n<contents>" into <out-dir>.
# Any *.ts already present in <out-dir> is deleted first, so files that were
# removed or renamed in the package cannot linger as stale copies.
render() {
  local out_dir="$1"
  local base
  local src

  mkdir -p "$out_dir"
  find "$out_dir" -maxdepth 1 -type f -name '*.ts' -delete

  shopt -s nullglob
  local files=("$SRC_DIR"/*.ts)
  shopt -u nullglob

  if [ "${#files[@]}" -eq 0 ]; then
    echo "sync_core_ts.sh: no .ts files found in $SRC_DIR" >&2
    exit 1
  fi

  for src in "${files[@]}"; do
    base="$(basename -- "$src")"
    {
      printf '%s\n' "$HEADER"
      cat -- "$src"
    } > "$out_dir/$base"
  done
}

if [ "$MODE" = "sync" ]; then
  render "$DEST_DIR"
  echo "sync_core_ts.sh: sync ${SRC_DIR#"$REPO_ROOT"/} -> $DEST_LABEL"
  exit 0
fi

# --- --check ----------------------------------------------------------------
# Regenerate into a temp dir and compare only the generated *.ts files, so
# unrelated editor-local files (Cache/, Workspaces/, ...) can never break CI.

TMP_ROOT="$(mktemp -d "${TMPDIR:-/tmp}/waykin-sync-core.XXXXXX")"
cleanup() { rm -rf -- "$TMP_ROOT"; }
trap cleanup EXIT

render "$TMP_ROOT/expected"
mkdir -p "$TMP_ROOT/actual"

if [ -d "$DEST_DIR" ]; then
  find "$DEST_DIR" -maxdepth 1 -type f -name '*.ts' -exec cp -p {} "$TMP_ROOT/actual" \;
fi

diff -ru \
  "$TMP_ROOT/actual" "$TMP_ROOT/expected" > "$TMP_ROOT/diff.txt" 2>&1 || true

if [ ! -s "$TMP_ROOT/diff.txt" ]; then
  echo "sync_core_ts.sh: $DEST_LABEL is in sync with packages/waykin-core-ts/src"
  exit 0
fi

echo "sync_core_ts.sh: $DEST_LABEL is OUT OF SYNC with packages/waykin-core-ts/src" >&2
echo >&2
cat "$TMP_ROOT/diff.txt" >&2
echo >&2
echo "Fix: bash scripts/sync_core_ts.sh   (then commit the regenerated files)" >&2
exit 1
